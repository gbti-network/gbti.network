#!/usr/bin/env node
// sow-291: generate house/campaigns.yml, the CODE-FREE projection of the coupon registry.
//
//   node scripts/build-campaign-manifest.mjs             # write the manifest
//   node scripts/build-campaign-manifest.mjs --check     # exit 1 if the committed manifest is out of date
//
// WHY THIS EXISTS. The coupon registry is moving off the public repository into KV, because a coupon code is
// a bearer credential and ours are published. Two consumers cannot follow it there: the lander parity guard
// is a unit test with no network and no secrets by project rule, and the Astro build runs on a runner with
// no KV binding. Both need to know which campaigns exist, what tier each confers and which page describes
// it. Neither needs the redeemable code.
//
// SO THIS IS A PROJECTION, NOT A SECOND REGISTRY, and the difference is the `--check` mode. A hand-maintained
// copy of a registry disagrees with it eventually and the disagreement is invisible until somebody reads a
// lander describing a tier they were not given, which is a defect that has already shipped here once.
//
// TODAY IT READS house/coupons.yml, because git is still the registry. sow-291 Phase 2 re-points the SOURCE
// to KV without changing the output shape or any consumer. That is the whole reason the projection lands
// first and alone: everything downstream is already reading the stable thing before the source moves.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { campaignManifest } from '../membership/invites.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'house/coupons.yml');
const OUT = path.join(ROOT, 'house/campaigns.yml');

const HEADER = `# GENERATED by scripts/build-campaign-manifest.mjs. Do not edit by hand.
#
# sow-291: the code-free projection of the coupon registry. It carries a campaign's stable IDENTITY and the
# terms a page may advertise. It NEVER carries the redeemable code, which is a bearer credential and does not
# belong in a public repository.
#
# \`id\` is the campaign's permanent public name. It is what house/grandfathered.yml records as
# \`reason: coupon:<ID>\`, what an issued invite stores as its \`campaign\`, and what LANDER_BY_CAMPAIGN keys on.
# It survives a code rotation untouched, which is what makes rotating a code cheap.
#
# Regenerate with \`node scripts/build-campaign-manifest.mjs\`. CI runs \`--check\` and fails on drift.
`;

/** The manifest as yaml text, header included. Pure over the parsed registry, so the test can call it too. */
export function renderManifest(parsed) {
  const { campaigns } = campaignManifest(parsed);
  const body = yaml.dump({ campaigns }, { lineWidth: 110, noRefs: true, sortKeys: false });
  return `${HEADER}\n${body}`;
}

function main() {
  const check = process.argv.includes('--check');
  let parsed;
  try {
    parsed = yaml.load(fs.readFileSync(SOURCE, 'utf8')) || {};
  } catch (e) {
    console.error(`build-campaign-manifest: cannot read ${path.relative(ROOT, SOURCE)}: ${e?.message ?? e}`);
    process.exitCode = 1;
    return;
  }
  const next = renderManifest(parsed);

  if (check) {
    // Fail loud on ABSENT as well as on different. A missing manifest is not "nothing to compare", it is the
    // guard having nothing to guard, and reporting that as a pass is how a check starts passing on zero.
    let current = null;
    try { current = fs.readFileSync(OUT, 'utf8'); } catch { current = null; }
    if (current === null) {
      console.error('build-campaign-manifest: house/campaigns.yml is MISSING. Run this script without --check.');
      process.exitCode = 1;
      return;
    }
    if (current !== next) {
      console.error('build-campaign-manifest: house/campaigns.yml is OUT OF DATE with house/coupons.yml.');
      console.error('  Run `node scripts/build-campaign-manifest.mjs` and commit the result.');
      process.exitCode = 1;
      return;
    }
    console.log(`build-campaign-manifest: house/campaigns.yml is current (${campaignManifest(parsed).campaigns.length} campaigns).`);
    return;
  }

  fs.writeFileSync(OUT, next);
  console.log(`build-campaign-manifest: wrote house/campaigns.yml (${campaignManifest(parsed).campaigns.length} campaigns, no codes).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
